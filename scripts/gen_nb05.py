md(
"## 5.3  TimeSeriesSplit -- Why Not KFold\n",
"\n",
"Standard KFold shuffles data randomly before creating folds. For time-series data this\n",
"causes **temporal leakage** -- fold 3 training data can contain January 28 trips while\n",
"fold 3 validation data contains January 3 trips (the model trains on the future).\n",
"\n",
"**TimeSeriesSplit always trains on past, validates on future:**\n",
"\n",
"```\n",
"Fold 1: Train [Jan 01-06]  |  Validate [Jan 07-12]\n",
"Fold 2: Train [Jan 01-12]  |  Validate [Jan 13-18]\n",
"Fold 3: Train [Jan 01-18]  |  Validate [Jan 19-24]\n",
"Fold 4: Train [Jan 01-22]  |  Validate [Jan 23-27]\n",
"Fold 5: Train [Jan 01-26]  |  Validate [Jan 27-31]\n",
"```\n",
"\n",
"Each validation fold is always in the future relative to its training fold.\n",
"This gives us 5 reliable, non-leaking validation scores to average for each trial.\n",
"\n",
"**Why 5 folds instead of 3?** More folds = more robust estimate of generalization error.\n",
"With 300k rows and 5 folds, each validation set has ~60k trips -- statistically stable.\n",
),

code(
"# Cell 4: Optuna objective function\n",
"# The objective is called once per trial. Optuna passes a 'trial' object with\n",
"# suggest_* methods that propose a parameter value and track the search history.\n",
"\n",
"CV_SPLITS = 5\n",
"tscv = TimeSeriesSplit(n_splits=CV_SPLITS)\n",
"\n",
"def objective(trial):\n",
"    params = {\n",
"        'n_estimators':       trial.suggest_int('n_estimators', 100, 600),\n",
"        'max_depth':          trial.suggest_int('max_depth', 3, 10),\n",
"        'learning_rate':      trial.suggest_float('learning_rate', 0.01, 0.3, log=True),\n",
"        'subsample':          trial.suggest_float('subsample', 0.5, 1.0),\n",
"        'colsample_bytree':   trial.suggest_float('colsample_bytree', 0.4, 1.0),\n",
"        'reg_alpha':          trial.suggest_float('reg_alpha', 1e-4, 10.0, log=True),\n",
"        'reg_lambda':         trial.suggest_float('reg_lambda', 1e-4, 10.0, log=True),\n",
"        'min_child_weight':   trial.suggest_int('min_child_weight', 1, 50),\n",
"        'gamma':              trial.suggest_float('gamma', 0.0, 5.0),\n",
"        'random_state':       RANDOM_STATE,\n",
"        'tree_method':        'hist',   # fastest CPU training method\n",
"        'n_jobs':             -1,\n",
"        'verbosity':          0,\n",
"    }\n",
"\n",
"    mae_scores = []\n",
"    for fold_idx, (tr_idx, val_idx) in enumerate(tscv.split(X_train)):\n",
"        X_tr, X_val = X_train[tr_idx], X_train[val_idx]\n",
"        y_tr, y_val = y_train[tr_idx], y_train[val_idx]\n",
"\n",
"        model = XGBRegressor(**params)\n",
"        model.fit(X_tr, y_tr,\n",
"                  eval_set=[(X_val, y_val)],\n",
"                  verbose=False)\n",
"\n",
"        y_pred_log = model.predict(X_val)\n",
"        # Evaluate on original seconds scale\n",
"        mae = mean_absolute_error(np.expm1(y_val), np.expm1(y_pred_log))\n",
"        mae_scores.append(mae)\n",
"\n",
"        # Report intermediate value to allow Optuna to prune bad trials\n",
"        trial.report(np.mean(mae_scores), fold_idx)\n",
"        if trial.should_prune():\n",
"            raise optuna.exceptions.TrialPruned()\n",
"\n",
"    return np.mean(mae_scores)\n",
"\n",
"print('Objective function defined.')\n",
"print(f'TimeSeriesSplit: {CV_SPLITS} folds')\n",
"print('Metric: Mean Absolute Error (seconds) on original scale')\n",
),

md(
"## 5.5  Hyperparameter Search Space -- Why These Bounds?\n",
"\n",
"| Parameter | Range | Reasoning |\n",
"|---|---|---|\n",
"| `n_estimators` | 100-600 | Too few = underfit, too many = diminishing returns + slow |\n",
"| `max_depth` | 3-10 | Shallow trees = underfitting, deep trees = overfitting leaf nodes |\n",
"| `learning_rate` | 0.01-0.3 (log scale) | Low LR needs more trees; log scale because we care about 0.01 vs 0.05 more than 0.2 vs 0.25 |\n",
"| `subsample` | 0.5-1.0 | Row sampling per tree -- below 0.5 loses too much signal |\n",
"| `colsample_bytree` | 0.4-1.0 | Feature sampling -- decorrelates trees, prevents feature dominance |\n",
"| `reg_alpha` | 1e-4 to 10 (log) | L1 regularization -- promotes sparsity in feature weights |\n",
"| `reg_lambda` | 1e-4 to 10 (log) | L2 regularization -- prevents large weights |\n",
"| `min_child_weight` | 1-50 | Minimum sum of instance weight in a leaf -- higher = more conservative splits |\n",
"| `gamma` | 0-5 | Minimum loss reduction to make a split -- higher = fewer splits = simpler trees |\n",
"\n",
"**Why `log=True` for learning_rate?** We sample logarithmically because the meaningful\n",
"range is geometric: 0.01, 0.03, 0.1, 0.3. Uniform sampling would waste 90% of trials\n",
"above 0.03 where diminishing returns kick in.\n",
"\n",
"**Why `tree_method='hist'`?** XGBoost's histogram-based training uses approximate split\n",
"finding with binned features. For 300k rows, this is 3-5x faster than exact split finding\n",
"with no meaningful accuracy loss. This is the default in XGBoost 2.x.\n",
),

