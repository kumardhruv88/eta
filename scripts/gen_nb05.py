"## Key Interview Questions -- Notebook 05\n",
"\n",
"**Q: Why Optuna over GridSearchCV?**  \n",
"A: GridSearch tries every combination -- 9 parameters with 5 values each = 5^9 = 2M trials.\n",
"Optuna's TPE sampler is Bayesian: it learns which regions of parameter space produce\n",
"low loss and focuses future trials there. Finds a good solution in 50 trials vs millions.\n",
"\n",
"**Q: What is TPE (Tree-structured Parzen Estimators)?**  \n",
"A: After each trial, TPE fits two density estimates: p(x|good) and p(x|bad) where\n",
"good/bad is defined by whether the trial beat the top-N% cutoff. Next trial samples\n",
"from the region that maximizes p(x|good)/p(x|bad). Effectively models 'where do\n",
"good parameters live?' and samples from there.\n",
"\n",
"**Q: What is MedianPruner?**  \n",
"A: After completing each fold in cross-validation, Optuna reports the intermediate\n",
"score. MedianPruner compares it to the median of all completed trials at the same\n",
"step. If the current trial is worse than the median, it prunes (stops) the trial.\n",
"Saves ~20-30% of compute by not finishing clearly inferior configurations.\n",
"\n",
"**Q: Why retrain on the full training set after tuning?**  \n",
"A: During CV, each fold only uses 80% of training data. The final model should use\n",
"all available historical data. We trust the CV-tuned hyperparameters generalize\n",
"because they performed well across 5 different time periods.\n",
"\n",
"**Q: What is hyperparameter overfitting?**  \n",
"A: After 50 trials of CV-based tuning, the best parameters may have exploited\n",
"idiosyncrasies in the validation folds rather than true generalizable patterns.\n",
"TimeSeriesSplit reduces this risk because 5 folds cover 5 different weeks --\n",
"parameters that consistently work across multiple time periods are genuinely robust.\n",
