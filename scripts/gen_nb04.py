md(
"## 4.16  A Note on Cross-Validation\n",
"\n",
"In this notebook we used a **simple chronological train/test split** for speed.\n",
"Each model was trained once on 80% of data and evaluated on 20%.\n",
"\n",
"**Limitation:** A single split is noisy -- the test set might happen to be an\n",
"unusually easy or hard period. One bad week in January could skew all metrics.\n",
"\n",
"**In Notebook 05 (hyperparameter tuning)** we will use:\n",
"```\n",
"TimeSeriesSplit(n_splits=5)\n",
"```\n",
"\n",
"**Why TimeSeriesSplit and NOT standard KFold?**\n",
"\n",
"KFold randomly shuffles the data before creating folds. This means:\n",
"- Fold 3 training set: trips from Jan 28, Jan 5, Jan 17 (shuffled)\n",
"- Fold 3 validation set: trips from Jan 2, Jan 25, Jan 8\n",
"\n",
"The model trains on January 28th data to predict January 2nd data.\n",
"This is temporal leakage -- the model sees the 'future' during training.\n",
"\n",
"TimeSeriesSplit guarantees:\n",
"- **Fold 1:** Train on Jan 1-6, validate on Jan 7-12\n",
"- **Fold 2:** Train on Jan 1-12, validate on Jan 13-18\n",
"- **Fold 3:** Train on Jan 1-18, validate on Jan 19-24\n",
"- etc.\n",
"\n",
"Always trains on past, validates on future -- exactly like production.\n",
),

md(
"## 4.17  Key Interview Questions -- Notebook 04\n",
"\n",
"**Q: Why do you always start with a baseline model?**  \n",
"A: The baseline establishes the minimum performance any model must exceed. If your\n",
"complex model barely beats 'always predict the mean', either the features carry no\n",
"signal or there is a bug. The baseline also gives a meaningful scale to improvements:\n",
"'XGBoost reduced error by 40% vs baseline' is far more informative than 'MAE = 85s'.\n",
"\n",
"**Q: What is the difference between bagging and boosting?**  \n",
"A: Bagging (Random Forest) builds trees in PARALLEL on random subsamples and averages\n",
"predictions -- reduces variance. Boosting (XGBoost) builds trees SEQUENTIALLY, each\n",
"correcting the errors of the previous -- reduces both bias and variance but risks\n",
"overfitting (mitigated by regularization and subsampling).\n",
"\n",
"**Q: Why does XGBoost usually beat Random Forest on tabular data?**  \n",
"A: Sequential error correction focuses effort on hard samples. Second-order gradient\n",
"optimization converges faster. Built-in L1/L2 regularization. Native missing value\n",
"handling. Row and column subsampling per tree prevents overfitting. In practice,\n",
"XGBoost consistently outperforms Random Forest on structured/tabular datasets.\n",
"\n",
"**Q: What is regularization and when do you use Ridge over Linear?**  \n",
"A: Regularization adds a penalty on large coefficients to the loss function, preventing\n",
"overfitting. Ridge (L2) shrinks all coefficients toward zero without eliminating any.\n",
"Use Ridge over Linear when: features are correlated (multicollinearity), when the\n",
"model overfits (gap between train and test score), or when you have more features\n",
"than samples.\n",
"\n",
"**Q: Why MAE over RMSE as the primary metric?**  \n",
"A: RMSE squares errors before averaging -- a few very long ETAs caused by traffic\n",
"incidents would disproportionately inflate RMSE and make it unrepresentative of\n",
"typical user experience. MAE gives equal weight to all errors, directly translating\n",
"to 'average user impact in seconds'. For operational decisions, MAE is more honest.\n",
"\n",
"**Q: Why TimeSeriesSplit instead of KFold?**  \n",
"A: KFold randomly shuffles data, allowing the model to train on 'future' trips to\n",
"predict 'past' trips -- temporal leakage. TimeSeriesSplit always trains on chronologically\n",
"earlier data and validates on later data, exactly simulating production conditions.\n",
"\n",
"**Q: What does R2 mean and what is a good value?**  \n",
"A: R2 (coefficient of determination) = 1 - (SS_residual / SS_total). It measures the\n",
"proportion of target variance explained by the model. 0.0 = same as predicting the mean.\n",
"1.0 = perfect predictions. For taxi ETA prediction, R2 of 0.5-0.7 is realistic given\n",
"inherent randomness in traffic conditions. Higher R2 often indicates data leakage.\n",
),

