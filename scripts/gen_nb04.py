"    print(f'{name:<30} MAE={mae:.1f}s  RMSE={rmse:.1f}s  MAPE={mape:.1f}%  R2={r2:.3f}')\n",
"    return {'model': name, 'MAE': mae, 'RMSE': rmse, 'MAPE': mape, 'R2': r2, 'fitted': model}\n",
