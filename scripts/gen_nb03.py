md(
"## 3.6  Target Variable Decision -- Should We Log-Transform?\n",
"\n",
"In Notebook 02 we saw that `eta_seconds` is right-skewed. We now choose whether to\n",
"train on the raw target or a transformed version.\n",
"\n",
"**Option A: Train on `eta_seconds` directly**  \n",
"- Model minimizes RMSE on raw scale\n",
"- Large ETAs (rare long pickups) dominate the loss function\n",
"- Model may underfit short ETAs (the majority) to better predict rare long ones\n",
"\n",
"**Option B: Train on `log1p(eta_seconds)` (log-transform)**  \n",
"- Model trains on a more symmetric, bell-shaped distribution\n",
"- All ETA ranges have more balanced influence on the loss\n",
"- Residuals are closer to normally distributed (satisfies linear model assumptions)\n",
"- After prediction: `predicted_eta = np.expm1(model.predict(X))`\n",
"- This is the approach used in production at Uber/Lyft for skewed regression targets\n",
"\n",
"**Decision: We train on `log1p(eta_seconds)` and evaluate on original seconds scale.**\n",
"\n",
"This is a principled, widely-used production technique for right-skewed regression targets.\n",
),

