"\n",
"Here is every feature we will build, and the business/statistical reason for each:\n",
"\n",
"**`pickup_hour`** (0-23)  \n",
"Driver availability and traffic patterns vary dramatically by hour. Rush hour means\n",
"more congestion and more demand -- longer ETA. 3am has less traffic but fewer drivers.\n",
"Hour captures complex non-linear temporal patterns that a tree model can learn.\n",
"\n",
"**`pickup_day_of_week`** (0-6, Mon=0)  \n",
"Monday morning vs Saturday night have completely different supply-demand dynamics.\n",
"Used both as numeric and to derive the binary flags below.\n",
"\n",
"**`is_weekend`** (0/1)  \n",
"Binary simplification of `pickup_day_of_week`. Our Mann-Whitney test in Notebook 02\n",
"confirmed a statistically significant ETA difference between weekdays and weekends.\n",
"\n",
"**`is_rush_hour`** (0/1)  \n",
"7-9am and 5-7pm -- peak congestion windows. Binary flag lets the model learn a step-change\n",
"in ETA (rush vs not-rush) rather than a smooth gradient over hours.\n",
"\n",
"**`is_night`** (0/1)  \n",
"10pm-5am. Late night has less traffic but also fewer available drivers -- complex trade-off\n",
"that a binary flag can help the model learn.\n",
"\n",
"**`PULocationID` -> Target Encoded**  \n",
"Pickup zone is one of the strongest predictors. Manhattan Midtown vs Queens residential\n",
"areas have fundamentally different driver supply. With ~265 unique zones, one-hot encoding\n",
"creates 265 sparse binary columns causing dimensionality and multicollinearity problems.\n",
"Target encoding replaces each zone with its smoothed mean ETA -- a single informative\n",
"numeric column. Industry standard for high-cardinality categoricals.\n",
"\n",
"**`DOLocationID` -> Target Encoded**  \n",
"Destination affects which drivers accept the trip. A driver near JFK may decline a\n",
"Queens pickup if the destination is the Bronx (bad repositioning). Same target encoding.\n",
"\n",
"**`operator`** (0=Uber, 1=Lyft)  \n",
