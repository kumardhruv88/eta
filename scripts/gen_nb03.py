"| `shared_request_flag` | Rider chose 'shared ride' option before requesting |\n",
"| `wav_request_flag` | Rider specified wheelchair accessible vehicle |\n",
"\n",
"### LEAKY -- known only AFTER the trip starts or ends\n",
"\n",
"| Column | Why it leaks |\n",
